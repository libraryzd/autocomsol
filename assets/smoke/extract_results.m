function data = extract_results(model)
x = linspace(0,0.1,101);
y = 0.01*ones(size(x));
temperature = mphinterp(model, 'T', 'coord', [x;y], 'dataset', 'acData', ...
    'solnum', 1, 'outersolnum', 1, 'unit', 'K', 'ext', 0);
assert(all(isfinite(temperature(:))) && isreal(temperature), ...
    'AutoCOMSOL:InvalidData', 'Nonfinite or complex temperatures.');
% Official mphint2 example uses the interface's boundary normal flux.
% A raw d(T,x) is not defined in every boundary evaluation context.
fluxExpression = 'ht.ntflux';
leftFlux = mphint2(model, fluxExpression, 'line', 'selection', 'left', ...
    'dataset', 'acData', 'solnum', 1, 'outersolnum', 1);
rightFlux = mphint2(model, fluxExpression, 'line', 'selection', 'right', ...
    'dataset', 'acData', 'solnum', 1, 'outersolnum', 1);
data = struct('x_m',x(:), 'y_m',y(:), 'temperature_K',temperature(:), ...
    'analytic_K',400-100*x(:)/0.1, 'leftFlux_W_per_m',leftFlux, ...
    'rightFlux_W_per_m',rightFlux, 'dataset','acData', 'solnum',1, ...
    'outersolnum',1, 'dimension',2, 'fluxExpression',fluxExpression);
end
